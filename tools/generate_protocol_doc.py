#!/usr/bin/env python
"""Render the authoring protocol diagram from its executable declaration.

Check the entire diagram directory: stale, missing and orphaned pages fail --check. Write
mode replaces current generated pages and removes obsolete ones carrying the generator
banner. Hand-written pages are preserved and reported for manual relocation. The protocol's
nested sections appear inside its single diagram."""

import sys
from pathlib import Path

from comeni_flow.diagram import to_mermaid
from mendel_authoring.protocol import PROTOCOL

DIAGRAMS = Path(__file__).parent.parent / "docs" / "explanation" / "diagrams"

FENCE = "`" * 3
BANNER = "<!-- generated by tools/generate_protocol_doc.py — do not edit -->\n"


def _page() -> str:
    header = "\n".join(
        [
            BANNER,
            f"# {PROTOCOL.title}",
            "",
            "**Generated from `mendel_authoring/protocol.py`**, which is also where the running "
            "state machine comes from, so this picture is the machine. Solid is built; dashed is "
            "designed and not built yet. A section marked *inside* is the steps one request "
            "takes; it never moves the conversation on by itself. The rules, the argument and the "
            "decision history are on [the protocol page](../authoring-protocol.md).",
        ]
    )
    return f"{header}\n\n{FENCE}mermaid\n{to_mermaid(PROTOCOL)}{FENCE}\n"


def pages() -> dict[str, str]:
    return {f"{PROTOCOL.slug}.md": _page()}


def main(argv: list[str] | None = None) -> int:
    argv = sys.argv[1:] if argv is None else argv
    want = pages()
    have = {p.name for p in DIAGRAMS.glob("*.md")} if DIAGRAMS.exists() else set()
    if "--check" in argv:
        wrong = sorted(
            name
            for name, text in want.items()
            if not (DIAGRAMS / name).exists() or (DIAGRAMS / name).read_text() != text
        )
        orphaned = sorted(have - set(want))
        for name in wrong + orphaned:
            print(
                f"docs/explanation/diagrams/{name} disagrees with protocol.py — run: "
                "uv run python tools/generate_protocol_doc.py"
            )
        return 1 if wrong or orphaned else 0
    DIAGRAMS.mkdir(parents=True, exist_ok=True)
    kept = []
    for name in sorted(have - set(want)):
        # **Only a page this generator wrote is removed**: one without the banner is somebody's
        # own writing, left where it is and reported (review of #134).
        if (DIAGRAMS / name).read_text().startswith(BANNER):
            (DIAGRAMS / name).unlink()
            print(f"removed docs/explanation/diagrams/{name}: nothing generates it any more")
        else:
            kept.append(name)
            print(f"docs/explanation/diagrams/{name} is not generated and was left alone; move it")
    for name, text in want.items():
        (DIAGRAMS / name).write_text(text)
    return 1 if kept else 0


if __name__ == "__main__":
    sys.exit(main())
