"""The files of a generated measuring step: its process, its runner and its pieces (#465).

A measuring step runs the same pieces the server runs, over all of the data, on a plain Python
image. Its module folder holds, beside `main.nf`, a Nextflow **module binary**
(`resources/usr/bin/`, staged into the task by `nextflow.enable.moduleBinaries`): a launcher named
for the step, the stdlib-only runner (`comeni_inspect`'s `core`, `outcome`, `records`, `stream`
and `measure_cli`) and each piece's code. The launcher carries every piece and threshold on its
own command line, so the step reads no registry and no YAML.

Everything here is a function of the declarations and the runner's source, so staging twice is
byte-identical, and `pipeline_file.stamp` records each file's digest in `pipeline.yml`.
"""

import importlib.metadata
import json
import re
import shutil
from pathlib import Path

from mendel_resolver.measure_steps import MeasureStep

RUNNER = ("__init__.py", "core.py", "outcome.py", "records.py", "stream.py", "measure_cli.py")
"""The runner's modules: the standard library and each other, nothing else (`test_core_stdlib`)."""

BIN = "resources/usr/bin"
EXECUTABLE = 0o755


def launcher_name(step: MeasureStep) -> str:
    return f"comeni-measure-{step.name.replace('_', '-')}"


def _piece(kind: str, piece) -> tuple[str, bytes]:
    """Where a piece's code goes in the step, and its bytes."""
    entry = Path(piece.entry).name
    code = (piece.folder / piece.entry).read_bytes()
    return f"comeni_measure/pieces/{kind}/{piece.id}/{entry}", code


def _runner_folder() -> Path:
    """Where the installed runner's source is. **Found, not imported**: `comeni_inspect` runs
    code it is handed, so this pure package copies its bytes and never loads it (the purity
    guard's arrow, `tests/support/purity.py`). `importlib.metadata` reads the installed
    package's own record: an editable install names its project folder, any other install
    holds the package itself."""
    dist = importlib.metadata.distribution("comeni-inspect")
    direct = json.loads(dist.read_text("direct_url.json") or "{}")
    url = direct.get("url", "")
    if direct.get("dir_info", {}).get("editable") and url.startswith("file://"):
        # Percent-decoded by hand: `urllib` is a transport and a pure package names none.
        path = re.sub(r"%([0-9A-Fa-f]{2})", lambda m: chr(int(m.group(1), 16)),
                      url.removeprefix("file://"))
        folder = Path(path) / "src" / "comeni_inspect"
    else:
        folder = Path(str(dist.locate_file("comeni_inspect")))
    if not (folder / "measure_cli.py").is_file():
        raise RuntimeError(f"comeni-inspect's runner is not at {folder}")
    return folder


def _main_nf(step: MeasureStep) -> str:
    contract = step.contract
    outputs = "\n".join(
        f'    tuple val(meta), path("*.measured.json"), emit: {port.name}'
        for port in contract.produces
    )
    measures = ", ".join(m.measures for m in step.measurers)
    return f"""// Generated by Mendel: {contract.provenance.source}. Do not edit.
// Measures {measures} over all of the data, with the code the server runs on an upload's
// head (#465). The facts land in {{outdir}}/{contract.nf_process.lower()}/<sample>.measured.json.
process {contract.nf_process} {{
    tag "$meta.id"
    label 'process_single'
    container '{contract.container}'

    input:
    tuple val(meta), path(data)

    output:
{outputs}

    script:
    // Run with `python3 -I`, found on the PATH the module binary joins: the launcher's mode
    // bit does not survive every bundle (a zip keeps none), and `-I` keeps a container's own
    // PYTHONPATH away from the runner.
    \"\"\"
    python3 -I "\\$(command -v {launcher_name(step)})" ${{data}} > "${{meta.id}}.measured.json"
    \"\"\"
}}
"""


def _launcher(step: MeasureStep, pieces: dict[str, str]) -> str:
    """A Python script naming every piece and threshold, run as the step's command."""
    if step.format is not None:
        args = ["--format", f"{step.format.id}@{step.format.version}={pieces['format']}"]
        for measurer in step.measurers:
            args += ["--measure", f"{measurer.id}@{measurer.version}={pieces[measurer.id]}",
                     "--decided", f"{measurer.id}={json.dumps(measurer.decided, sort_keys=True)}"]
        codecs = {
            ext: f"{codec.id}@{codec.version}={pieces['codec:' + codec.id]}"
            for codec in step.codecs for ext in sorted(codec.extensions)
        }
    else:
        (measurer,) = step.measurers
        args = ["--parser", f"{measurer.id}@{measurer.version}={pieces[measurer.id]}",
                "--decided", f"{measurer.id}={json.dumps(measurer.decided, sort_keys=True)}"]
        codecs = {}
    return f'''#!/usr/bin/env python3
"""{step.contract.nf_process}: generated by Mendel from {step.contract.provenance.source}.

Runs the measurer pieces beside it over the files it is given, whole, and prints one report.
Do not edit: `pipeline.yml` records this file's digest."""

import sys
from pathlib import Path

HERE = Path(__file__).resolve().parent / "comeni_measure"
sys.path.insert(0, str(HERE))

from comeni_inspect.measure_cli import main  # noqa: E402

ARGS = {json.dumps(args, indent=4)}
CODECS = {json.dumps(codecs, indent=4, sort_keys=True)}
"""By file extension, as the server matches an upload: a codec opens every file or none."""


def _here(spelled):
    """`id@version=relative` to the pieces beside this file."""
    pinned, sep, path = spelled.partition("=")
    return f"{{pinned}}={{HERE / path}}" if sep and path.startswith("pieces/") else spelled


files = sys.argv[1:]
# The longest extension first, so `.tar.gz` would win over `.gz`.
codec = next((CODECS[ext] for ext in sorted(CODECS, key=len, reverse=True)
              if files and all(name.endswith(ext) for name in files)), None)
args = [_here(a) for a in ARGS] + (["--codec", _here(codec)] if codec else [])
sys.exit(main(args + files))
'''


def files(step: MeasureStep) -> dict[str, bytes]:
    """Every file of the step's module folder, by its path inside that folder."""
    found: dict[str, bytes] = {}
    pieces: dict[str, str] = {}
    if step.format is not None:
        where, data = _piece("formats", step.format)
        found[f"{BIN}/{where}"], pieces["format"] = data, where.removeprefix("comeni_measure/")
        for codec in step.codecs:
            where, data = _piece("codecs", codec)
            found[f"{BIN}/{where}"] = data
            pieces["codec:" + codec.id] = where.removeprefix("comeni_measure/")
    for measurer in step.measurers:
        where, data = _piece("measures", measurer)
        found[f"{BIN}/{where}"], pieces[measurer.id] = data, where.removeprefix("comeni_measure/")
    runner = _runner_folder()
    for name in RUNNER:
        found[f"{BIN}/comeni_measure/comeni_inspect/{name}"] = (runner / name).read_bytes()
    found[f"{BIN}/{launcher_name(step)}"] = _launcher(step, pieces).encode()
    found["main.nf"] = _main_nf(step).encode()
    return dict(sorted(found.items()))


def write(step: MeasureStep, folder: Path) -> None:
    """Write the step's module folder afresh; the launcher is executable.

    Cleared first, so a file an earlier version of a piece left behind is never staged,
    digested and shipped: the folder is exactly `files(step)`."""
    if folder.exists():
        shutil.rmtree(folder)
    for name, data in files(step).items():
        path = folder / name
        path.parent.mkdir(parents=True, exist_ok=True)
        path.write_bytes(data)
        path.chmod(EXECUTABLE if name == f"{BIN}/{launcher_name(step)}" else 0o644)
